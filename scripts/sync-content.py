"""Copy markdown pages into TypeScript string modules the web app imports.
Run after editing anything in docs/ that is served by the app."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
PAGES = {
    "docs/DOCUMENTATION.md": ("web/src/content/documentation.ts", "DOCUMENTATION_MD"),
}
for src, (dst, name) in PAGES.items():
    md = (root / src).read_text()
    escaped = md.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    (root / dst).write_text(f"// Generated by scripts/sync-content.py from {src}. Do not edit by hand.\nexport const {name} = `{escaped}`;\n")
    print(f"synced {src} -> {dst} ({len(md)} chars)")
